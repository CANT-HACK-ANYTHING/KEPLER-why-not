def calculate_modbus_crc16(data: bytes) -> int:
    crc = 0xFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            if crc & 0x0001:
                crc = (crc >> 1) ^ 0xA001
            else:
                crc >>= 1
    return crc

def test_pzem_modbus_crc():
    # PZEM-004T v3.0 standard read command: 01 04 00 00 00 0A
    # Modbus CRC16 returns 0x0D70. On the wire, transmitted Low byte first: [0x70, 0x0D]
    cmd = bytes([0x01, 0x04, 0x00, 0x00, 0x00, 0x0A])
    expected_crc = 0x0D70
    computed_crc = calculate_modbus_crc16(cmd)
    assert computed_crc == expected_crc, f"CRC mismatch: {hex(computed_crc)} != {hex(expected_crc)}"
    low_byte = computed_crc & 0xFF
    high_byte = (computed_crc >> 8) & 0xFF
    assert [low_byte, high_byte] == [0x70, 0x0D], f"Wire byte order mismatch: {[low_byte, high_byte]}"
    print("✓ PZEM-004T Modbus-RTU CRC16 calculation verified: 0x0D70 (Wire bytes: [0x70, 0x0D])")

def test_firmware_hmac_bit_identical():
    node_secret = "relay_ev_hardware_master_secret_2026"
    session_id = "REV-TEST-992144"
    energy_kwh = 8.420
    actual_cost = 84.20

    # Backend formula
    backend_signature = compute_node_hmac(session_id, energy_kwh, actual_cost, node_secret)

    # Firmware formula: snprintf(msg, "%s:%.3f:%.2f", session_id, energy, cost)
    firmware_msg = f"{session_id}:{energy_kwh:.3f}:{actual_cost:.2f}".encode("utf-8")
    firmware_signature = hmac.new(node_secret.encode("utf-8"), firmware_msg, hashlib.sha256).hexdigest()

    assert backend_signature == firmware_signature, "Firmware HMAC does not match backend HMAC!"
    print(f"✓ Firmware & Backend HMAC-SHA256 Bit-for-bit identical: {firmware_signature}")

    # Verify signature validator accepts it
    is_valid, is_authentic = verify_node_receipt_signature(
        session_id, energy_kwh, actual_cost, firmware_signature, node_secret
    )
    assert is_valid and is_authentic, "Backend rejected firmware HMAC signature!"
    print("✓ Backend verify_node_receipt_signature accepts firmware HMAC: authentic=True")

def test_firmware_receipt_json_validation():
    node_secret = "relay_ev_hardware_master_secret_2026"
    session_id = "REV-OFFLINE-789"
    node_id = "RelayEV-Node-01"
    user_id = "user_88"
    energy_kwh = 4.500
    rate = 10.00
    actual_cost = energy_kwh * rate
    timestamp = 1793018200
    nonce = "nonce_firmware_test_123"

    signature = compute_node_hmac(session_id, energy_kwh, actual_cost, node_secret)

    # Simulate receipt generated by C++ createReceiptJson()
    receipt_json = {
        "session_id": session_id,
        "node_id": node_id,
        "user_id": user_id,
        "energy_consumed_kwh": energy_kwh,
        "actual_cost": actual_cost,
        "timestamp": timestamp,
        "nonce": nonce,
        "node_signature": signature
    }

    # Validate against Pydantic schema
    receipt_obj = ReceiptData(**receipt_json)
    assert receipt_obj.session_id == session_id
    assert receipt_obj.actual_cost == 45.00
    print("✓ Firmware JSON receipt strictly conforms to Pydantic ReceiptData schema")

    # Validate against StopRequest schema
    stop_request = ChargeStopRequest(**receipt_json)
    assert stop_request.energy_consumed_kwh == 4.500
    print("✓ Firmware JSON receipt strictly conforms to ChargeStopRequest schema")

