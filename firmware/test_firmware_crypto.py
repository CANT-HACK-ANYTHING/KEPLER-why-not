def test_live_cloud_integration_with_firmware_receipt():
    import urllib.request
    
    BASE_URL = "http://localhost:8000"
    
    # 1. Start charging session
    start_payload = json.dumps({
        "user_id": "user_88",
        "node_id": "RelayEV-Node-01",
        "escrow_amount": 100.00
    }).encode("utf-8")
    
    req = urllib.request.Request(
        f"{BASE_URL}/api/charge/start",
        data=start_payload,
        headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(req) as resp:
        start_res = json.loads(resp.read().decode("utf-8"))
        
    session_id = start_res["session_id"]
    node_id = start_res["node_id"]
    user_id = start_res["user_id"]
    print(f"✓ Cloud created session: {session_id} (Escrow: ₹{start_res['escrow_amount']})")
    
    # 2. Firmware simulates charging up to 8.420 kWh cutoff
    energy_kwh = 8.420
    actual_cost = energy_kwh * start_res["rate_per_kwh"]
    node_secret = "relay_ev_hardware_master_secret_2026"
    
    # Compute firmware HMAC
    signature = compute_node_hmac(session_id, energy_kwh, actual_cost, node_secret)
    
    stop_payload = json.dumps({
        "session_id": session_id,
        "node_id": node_id,
        "user_id": user_id,
        "energy_consumed_kwh": energy_kwh,
        "actual_cost": actual_cost,
        "node_signature": signature,
        "nonce": f"nonce_firmware_{session_id}"
    }).encode("utf-8")
    
    stop_req = urllib.request.Request(
        f"{BASE_URL}/api/charge/stop",
        data=stop_payload,
        headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(stop_req) as resp:
        stop_res = json.loads(resp.read().decode("utf-8"))
        
    assert stop_res["status"] == "SETTLED"
    assert stop_res["signature_verified"] is True
    assert stop_res["refund_amount"] == round(100.00 - actual_cost, 2)
    print(f"✓ Cloud settled session {session_id} with hardware HMAC: refund ₹{stop_res['refund_amount']:.2f}")

