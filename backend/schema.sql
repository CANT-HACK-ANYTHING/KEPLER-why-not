-- ============================================================
-- RPC: settle_charge_transaction
-- Atomic, race-condition proof financial settlement for RelayEV.
-- Moves funds from locked_escrow_balance back to wallet_balance (refund),
-- transitions transaction status to 'settled', and releases the node.
-- ============================================================
CREATE OR REPLACE FUNCTION settle_charge_transaction(
    p_tx_id UUID,
    p_user_id VARCHAR(64),
    p_node_id VARCHAR(64),
    p_escrow_amount NUMERIC(10, 2),
    p_final_cost NUMERIC(10, 2),
    p_refund_amount NUMERIC(10, 2),
    p_kwh_delivered NUMERIC(8, 3),
    p_offline_receipt JSONB,
    p_signature TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_tx_status VARCHAR(32);
    v_user_locked_balance NUMERIC(10, 2);
BEGIN
    -- 1. Lock and verify the transaction record to prevent double-settlement
    SELECT status INTO v_current_tx_status
    FROM transactions
    WHERE id = p_tx_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Transaction % not found', p_tx_id;
    END IF;

    IF v_current_tx_status = 'settled' THEN
        RAISE EXCEPTION 'Transaction % has already been settled', p_tx_id;
    END IF;

    -- 2. Lock the user row to prevent concurrent balance manipulation
    SELECT locked_escrow_balance INTO v_user_locked_balance
    FROM users
    WHERE id = p_user_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'User % not found', p_user_id;
    END IF;

    IF v_user_locked_balance < p_escrow_amount THEN
        RAISE EXCEPTION 'User % locked_escrow_balance (%) is less than escrow_amount (%)', 
            p_user_id, v_user_locked_balance, p_escrow_amount;
    END IF;

    -- 3. Atomic Balance Updates:
    -- Remove the initial escrow hold and credit back the unused change
    UPDATE users
    SET 
        locked_escrow_balance = locked_escrow_balance - p_escrow_amount,
        wallet_balance = wallet_balance + p_refund_amount,
        updated_at = NOW()
    WHERE id = p_user_id;

    -- 4. Transition transaction to 'settled' with audited metrics and receipt proof
    UPDATE transactions
    SET
        status = 'settled',
        energy_kwh_delivered = p_kwh_delivered,
        final_cost = p_final_cost,
        refund_amount = p_refund_amount,
        offline_receipt_json = p_offline_receipt,
        offline_signature = p_signature,
        completed_at = NOW()
    WHERE id = p_tx_id;

    -- 5. Release node back to 'available' and update last_synced_at
    UPDATE nodes
    SET
        status = 'available',
        last_synced_at = NOW()
    WHERE id = p_node_id;

    RETURN jsonb_build_object(
        'status', 'settled',
        'tx_id', p_tx_id,
        'final_cost', p_final_cost,
        'refund_amount', p_refund_amount,
        'kwh_delivered', p_kwh_delivered
    );
END;
$$;


-- ============================================================
-- RPC: lock_escrow_for_charge
-- Atomically checks user balance, locks escrow amount,
-- sets node to 'busy', and inserts a pending transaction record.
-- ============================================================
CREATE OR REPLACE FUNCTION lock_escrow_for_charge(
    p_user_id VARCHAR(64),
    p_node_id VARCHAR(64),
    p_escrow_amount NUMERIC(10, 2),
    p_tariff_snapshot NUMERIC(8, 2),
    p_max_kwh NUMERIC(8, 2)
)
RETURNS UUID
LANGUAGE plpgsql
AS $$
DECLARE
    v_user_wallet NUMERIC(10, 2);
    v_node_status VARCHAR(32);
    v_tx_id UUID;
BEGIN
    -- 1. Lock user row and verify sufficient funds
    SELECT wallet_balance INTO v_user_wallet
    FROM users
    WHERE id = p_user_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'User % not found', p_user_id;
    END IF;

    IF v_user_wallet < p_escrow_amount THEN
        RAISE EXCEPTION 'Insufficient balance: wallet has %, requested %', v_user_wallet, p_escrow_amount;
    END IF;

    -- 2. Lock node row and verify availability
    SELECT status INTO v_node_status
    FROM nodes
    WHERE id = p_node_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Node % not found', p_node_id;
    END IF;

    IF v_node_status <> 'available' THEN
        RAISE EXCEPTION 'Node % is currently % and not available', p_node_id, v_node_status;
    END IF;

    -- 3. Atomically move funds from wallet to locked escrow
    UPDATE users
    SET
        wallet_balance = wallet_balance - p_escrow_amount,
        locked_escrow_balance = locked_escrow_balance + p_escrow_amount,
        updated_at = NOW()
    WHERE id = p_user_id;

    -- 4. Mark node as busy
    UPDATE nodes
    SET status = 'busy'
    WHERE id = p_node_id;

    -- 5. Insert new transaction in 'escrow_locked' state
    INSERT INTO transactions (
        user_id,
        node_id,
        escrow_amount,
        tariff_per_kwh_snapshot,
        max_kwh_allowed,
        status,
        started_at
    )
    VALUES (
        p_user_id,
        p_node_id,
        p_escrow_amount,
        p_tariff_snapshot,
        p_max_kwh,
        'escrow_locked',
        NOW()
    )
    RETURNING id INTO v_tx_id;

    RETURN v_tx_id;
END;
$$;
