-- ============================================================
-- RelayEV Cloud Schema (Supabase / PostgreSQL)
-- Offline-First Rural EV Charging Mesh
-- ============================================================

-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Clean up existing tables if rebuilding
DROP TABLE IF EXISTS transactions CASCADE;
DROP TABLE IF EXISTS nodes CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ============================================================
-- TABLE: users
-- Represents EV drivers and host accounts.
-- (Includes dummy user_88 for sprint testing)
-- ============================================================
CREATE TABLE users (
    id VARCHAR(64) PRIMARY KEY, -- e.g., 'user_88' or UUID
    full_name VARCHAR(128) NOT NULL,
    email VARCHAR(255) UNIQUE,
    wallet_balance NUMERIC(10, 2) NOT NULL DEFAULT 500.00 CHECK (wallet_balance >= 0),
    locked_escrow_balance NUMERIC(10, 2) NOT NULL DEFAULT 0.00 CHECK (locked_escrow_balance >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- TABLE: nodes
-- Offline EV Charging Stations (ESP32 micro-hubs).
-- Stations do NOT have internet; coordinates and tariff are registered here.
-- ============================================================
CREATE TABLE nodes (
    id VARCHAR(64) PRIMARY KEY, -- e.g. 'node_esp32_rural_01'
    name VARCHAR(128) NOT NULL,
    description TEXT,
    
    -- Geospatial coordinates for Cloud Map Rendering
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    address_reference TEXT,
    
    -- Operational parameters
    tariff_per_kwh NUMERIC(8, 2) NOT NULL DEFAULT 15.00, -- Rate in local currency per kWh
    max_power_kw NUMERIC(6, 2) NOT NULL DEFAULT 3.30,   -- e.g. 3.3 kW AC rural charger
    
    -- Cryptographic Verification
    -- Public key or shared secret used to verify receipts generated by this offline node
    public_key TEXT,
    
    -- Telemetry relayed from previous drivers
    status VARCHAR(32) NOT NULL DEFAULT 'available', -- 'available', 'busy', 'offline_fault'
    last_synced_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- TABLE: transactions
-- Financial Escrow Engine & Session Records.
-- Bridges Cloud Escrow <-> Offline BLE Session <-> Final Settlement.
-- ============================================================
CREATE TABLE transactions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id VARCHAR(64) NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    node_id VARCHAR(64) NOT NULL REFERENCES nodes(id) ON DELETE RESTRICT,
    
    -- Escrow details
    escrow_amount NUMERIC(10, 2) NOT NULL CHECK (escrow_amount > 0),
    tariff_per_kwh_snapshot NUMERIC(8, 2) NOT NULL,
    max_kwh_allowed NUMERIC(8, 2) NOT NULL,
    
    -- Status pipeline
    -- 'escrow_locked': Cloud has locked funds, issued token
    -- 'charging_active': Phone confirmed token sent to ESP32
    -- 'settled': Signed offline receipt submitted and verified
    -- 'refunded': Session aborted before charging or timed out
    status VARCHAR(32) NOT NULL DEFAULT 'escrow_locked',
    
    -- Cryptographic Proofs
    session_token TEXT,         -- Signed JWT passed to ESP32
    offline_receipt_json JSONB, -- JSON payload received from ESP32 BLE
    offline_signature TEXT,     -- ECDSA / HMAC signature produced by ESP32
    
    -- Final Metered Metrics (Filled on settlement)
    energy_kwh_delivered NUMERIC(8, 3) DEFAULT 0.000,
    final_cost NUMERIC(10, 2) DEFAULT 0.00,
    refund_amount NUMERIC(10, 2) DEFAULT 0.00,
    
    -- Timestamps
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ
);

