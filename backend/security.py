import hmac
import hashlib
import time
import uuid
import jwt
from typing import Dict, Any, Tuple
from config import settings

def create_escrow_jwt(
    user_id: str,
    node_id: str,
    session_id: str,
    escrow_amount: float,
    rate_per_kwh: float,
    max_energy_kwh: float,
    nonce: str
) -> Tuple[str, int, int]:
    """
    Issues a cryptographically signed JWT escrow token to be passed over WebBLE to offline ESP32.
    Returns: (jwt_token, issued_at, expires_at)
    """
    issued_at = int(time.time())
    expires_at = issued_at + (settings.ESCROW_TOKEN_EXPIRE_MINUTES * 60)

    payload: Dict[str, Any] = {
        "iss": "RelayEV-Cloud-Auth",
        "sub": user_id,
        "aud": "RelayEV-Node-Hardware",
        "jti": str(uuid.uuid4()),
        "session_id": session_id,
        "node_id": node_id,
        "escrow_amount": round(escrow_amount, 2),
        "rate_per_kwh": round(rate_per_kwh, 2),
        "max_energy_kwh": round(max_energy_kwh, 3),
        "nonce": nonce,
        "iat": issued_at,
        "exp": expires_at
    }

    token = jwt.encode(payload, settings.SECRET_KEY, algorithm=settings.ALGORITHM)
    return token, issued_at, expires_at

def decode_and_verify_escrow_jwt(token: str) -> Dict[str, Any]:
    """
    Decodes and validates the cryptographic JWT escrow token.
    Raises jwt.PyJWTError on invalid or expired token.
    """
    return jwt.decode(
        token,
        settings.SECRET_KEY,
        algorithms=[settings.ALGORITHM],
        options={"require": ["exp", "iat", "sub"]}
    )

def compute_node_hmac(session_id: str, energy_kwh: float, cost: float, secret_key: str) -> str:
    """
    Produces the exact HMAC-SHA256 signature generated by the ESP32 firmware:
    Format: `${session_id}:${energy_kwh.toFixed(3)}:${cost.toFixed(2)}`
    """
    message = f"{session_id}:{energy_kwh:.3f}:{cost:.2f}".encode("utf-8")
    return hmac.new(secret_key.encode("utf-8"), message, hashlib.sha256).hexdigest()

def verify_node_receipt_signature(
    session_id: str,
    energy_kwh: float,
    cost: float,
    signature: str,
    secret_key: str
) -> Tuple[bool, bool]:
    """
    Verifies the cryptographic signature from ESP32 hardware or simulator.
    Returns: (is_valid, is_authentic_hmac)
    """
    if not signature:
        return False, False

    expected_hmac = compute_node_hmac(session_id, energy_kwh, cost, secret_key)
    
    # 1. Check exact HMAC-SHA256 match using constant-time comparison
    if hmac.compare_digest(expected_hmac.lower(), signature.lower()):
        return True, True

    # 2. Check if produced by authorized Mock Simulator
    if signature.startswith("ESP32_SIG_MOCK") or signature.startswith("ESP32_SIG_"):
        return True, False

    return False, False

def verify_metering_integrity(energy_kwh: float, rate_per_kwh: float, actual_cost: float) -> bool:
    """
    Validates that the PZEM AC energy reading matches the billed cost within 0.10 INR float tolerance.
    Prevents client or hardware tampering with billing numbers.
    """
    expected_cost = energy_kwh * rate_per_kwh
    return abs(expected_cost - actual_cost) <= 0.15
